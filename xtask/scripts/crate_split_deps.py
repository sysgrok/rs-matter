"""Check the module dependencies of `rs-matter` against the planned crate split.

Maps each module of `rs-matter/src` to the crate it goes to in
`docs/crate-split-design.md`, and lists the `crate::` references that cross a
crate boundary the design does not allow. Exits with 1 if there are any.

This is a temporary aid for the work inside the current crate. Once the crates
exist, Cargo enforces the same rules and the script can go.

The check is textual. It does not see code generated by macros, and it skips
`#[cfg(test)]` modules, as tests may use dev-dependencies.

Usage: crate_split_deps.py [<path to rs-matter/src>] [--edges]

  --edges    also print the crate graph that the references form
"""

import os
import re
import sys
from collections import defaultdict

# The crates each crate may depend on. `error` and `utils` are added for all
# crates but `error` below.
ALLOWED = {
    'error': set(),
    'utils': {'error'},
    'tlv': set(),
    'crypto': {'tlv'},
    'cert': {'crypto', 'tlv'},
    'pairing': {'crypto', 'tlv'},
    'im-base': {'tlv'},
    'dm-base': {'im-base', 'crypto', 'tlv'},
    'dm-clusters': {'dm-base', 'im-base', 'tlv'},
    'node': {'dm-base', 'im-base', 'cert', 'crypto', 'pairing', 'tlv'},
    'im': {'node', 'dm-base', 'im-base', 'cert', 'crypto', 'tlv'},
    'dm': {'node', 'dm-clusters', 'dm-base', 'im-base', 'cert', 'crypto', 'pairing', 'tlv'},
    'onboard': {'node', 'dm-clusters', 'dm-base', 'im-base', 'cert', 'crypto', 'pairing', 'tlv'},
}
for crate, deps in ALLOWED.items():
    if crate != 'error':
        deps |= {'utils', 'error'}

# Source file (relative to `src`, without `.rs`) -> crate. The first match wins.
FILE_RULES = [
    (r'^error$', 'error'),
    (r'^utils/zbus', 'node'),
    (r'^utils(/|$)', 'utils'),
    (r'^tlv(/|$)', 'tlv'),
    (r'^(crypto|group_keys)(/|$)', 'crypto'),
    (r'^(cert|attest)(/|$)', 'cert'),
    (r'^pairing(/|$)', 'pairing'),
    (r'^im/encoding(/|$)', 'im-base'),
    (r'^im/client$', 'node'),
    (r'^(im|respond)(/|$)', 'im'),
    (r'^dm/devices/test$', 'node'),
    (r'^(dm/types|dm/devices|persist)(/|$)', 'dm-base'),
    (r'^dm/clusters$', 'dm-clusters'),
    (r'^dm/', 'dm'),
    (r'^pics$', 'dm'),
    (r'^dm$', 'dm-base'),
    (r'^onboard(/|$)', 'onboard'),
    (r'^(lib|fmt|transport|sc|fabric|acl|failsafe|handover|bdx|ota|rtc|icd|groupcast|basic_info|networks)(/|$)', 'node'),
]

# Referenced path (after `crate::`) -> crate. The first match wins. `None`
# marks paths that every crate has (logging macros, re-exports).
PATH_RULES = [
    (r'^error\b', 'error'),
    (r'^utils::zbus', 'node'),
    (r'^utils\b', 'utils'),
    (r'^tlv\b', 'tlv'),
    (r'^(crypto|group_keys)\b', 'crypto'),
    (r'^(cert|attest)\b', 'cert'),
    (r'^pairing\b', 'pairing'),
    (r'^im::encoding\b', 'im-base'),
    (r'^im::client\b', 'node'),
    # `im::X` is the encoding (through a glob re-export), unless X is an item of the engine
    (r'^im::(subscriptions|events|invoker|expand|busy|context|report|InteractionModel|ImStats|DeviceLoad'
     r'|ReportDataHandler|ReportContext|SubscriptionCtx|expand_\w+|InteractionModelState|IM_)\b', 'im'),
    (r'^im\b', 'im-base'),
    (r'^respond\b', 'im'),
    (r'^dm::clusters::decl\b', 'dm-clusters'),
    (r'^dm::clusters\b', 'dm'),
    (r'^dm::(endpoints|networks)\b', 'dm'),
    (r'^dm::devices::test\b', 'node'),
    (r'^dm\b', 'dm-base'),
    (r'^persist\b', 'dm-base'),
    (r'^pics\b', 'dm'),
    (r'^onboard\b', 'onboard'),
    (r'^(transport|sc|fabric|acl|failsafe|handover|bdx|ota|rtc|icd|groupcast|basic_info|networks'
     r'|Matter|MatterState|BootReason|BasicCommData|MatterLocalService|MATTER_PORT|test)\b', 'node'),
    (r'^(reexport|alloc|fmt|info|warn|debug|trace|unwrap|panic|todo|unreachable|assert\w*)\b', None),
    (r'^(with|except|handler_chain_type|devices|attribute_enum)\b', 'dm-base'),
    (r'^(clusters|root_endpoint|__\w+)\b', 'dm'),
    (r'^bitflags_tlv\b', 'tlv'),
]

# Files of modules that are declared `#[cfg(test)]`
TEST_FILES = {'dm/clusters/app/test_util'}

USE_GROUP = re.compile(r'use crate::\{(.*?)\};', re.S)
PATH = re.compile(r'(?<![\w$])\$?crate::([A-Za-z_]\w*(?:::[A-Za-z_]\w*)*)')


def crate_of_file(rel):
    for pattern, crate in FILE_RULES:
        if re.search(pattern, rel):
            return crate
    sys.exit(f'No crate for {rel}.rs; add a rule to FILE_RULES')


def crate_of_path(path):
    for pattern, crate in PATH_RULES:
        if re.search(pattern, path):
            return crate
    return '?'


def strip(src):
    """Blank out comments and `#[cfg(test)]` items, keeping the line numbers."""
    out = []
    lines = src.split('\n')
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith('#[cfg(test)]'):
            # Skip the item that follows: up to its matching closing brace,
            # or up to the `;` of a one-line item
            j = i + 1
            while j < len(lines) and '{' not in lines[j] and not lines[j].rstrip().endswith(';'):
                j += 1
            if j < len(lines) and '{' in lines[j]:
                depth = 0
                while j < len(lines):
                    depth += lines[j].count('{') - lines[j].count('}')
                    j += 1
                    if depth <= 0:
                        break
                out.extend([''] * (j - i))
                i = j
            else:
                out.extend([''] * (j + 1 - i))
                i = j + 1
            continue
        if line.startswith('//'):
            out.append('')
        else:
            out.append(re.sub(r'//.*$', '', lines[i]))
        i += 1
    return '\n'.join(out)


def paths_in(text):
    """Return the `(line, path)` of each `crate::` path in `text`."""
    found = []
    # The items of `use crate::{a::b, c::{d, e}}`, by their leading segments
    for m in USE_GROUP.finditer(text):
        line = text.count('\n', 0, m.start()) + 1
        for item in re.findall(r'(?:^|[,{]\s*)([A-Za-z_]\w*(?:::[A-Za-z_]\w*)*)', m.group(1)):
            found.append((line, item))
    for m in PATH.finditer(text):
        line = text.count('\n', 0, m.start()) + 1
        found.append((line, m.group(1)))
    return found


def main():
    args = [arg for arg in sys.argv[1:] if not arg.startswith('--')]
    show_edges = '--edges' in sys.argv
    root = args[0] if args else os.path.join(os.path.dirname(__file__), '..', '..', 'rs-matter', 'src')

    violations = defaultdict(set)
    edges = defaultdict(set)

    for dir_path, _, file_names in os.walk(root):
        for file_name in file_names:
            if not file_name.endswith('.rs'):
                continue
            path = os.path.join(dir_path, file_name)
            rel = os.path.relpath(path, root)[:-3].replace(os.sep, '/')
            if rel in TEST_FILES:
                continue
            src_crate = crate_of_file(rel)
            with open(path, encoding='utf-8') as f:
                text = strip(f.read())
            for line, ref in paths_in(text):
                if ref in ('self', 'super'):
                    continue
                dst_crate = crate_of_path(ref)
                if dst_crate is None or dst_crate == src_crate:
                    continue
                edges[src_crate].add(dst_crate)
                if dst_crate not in ALLOWED[src_crate]:
                    violations[(src_crate, dst_crate)].add(f'{rel}.rs:{line}: crate::{ref}')

    if show_edges:
        for crate in sorted(edges):
            print(f'{crate:12} -> {", ".join(sorted(edges[crate]))}')
        print()

    total = 0
    for (src_crate, dst_crate), refs in sorted(violations.items()):
        print(f'== {src_crate} -> {dst_crate}: {len(refs)}')
        for ref in sorted(refs):
            print(f'   {ref}')
        total += len(refs)
    print(f'\n{total} references across boundaries the design does not allow')

    return 1 if total else 0


if __name__ == '__main__':
    sys.exit(main())
